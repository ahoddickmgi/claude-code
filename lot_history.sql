            ELSE
                (CASE WHEN OIAT.SUM_ARATAMT = 0 THEN OIAT.SUM_QRATAMT ELSE OIAT.SUM_ARATAMT END)
                * (OIL.LINEQTY / OITQ.TOTAL_INV_QTY)
        END AS ACCAMT_0
    FROM OUTBOUND_INVOICE_LINES OIL
    JOIN OUTBOUND_INVOICE_TOTAL_QTY OITQ
